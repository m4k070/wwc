; demo/scroll.asm — CA デモ映像用の最小 ROM (rgbds)
;
; 目的: CA (sm83_full) の実行と gbfs の PPU 出力を並べて撮るための題材。
; 効果は 2 つ、どちらも「走査線を描いている最中にレジスタを書き換える」形:
;
;   1. 走査線ごとに SCX を 1 進める -> 縞が 45 度に傾いて流れる
;   2. 12 走査線ごとに BGP を 1 段上げる -> 模様が濃くなっていく (起動演出の見え方)
;
; フレーム単位の動き (VBlank で SCY を更新する等) は使えない。PPU は 1 フレームを
; 17,556 バス周期かけて描くので、1 フレームぶんの撮影では 1 回も変化しない。
; 見える動きは「描いている最中のレジスタを書き換える」形だけ。
;
; BGP は $00 で LCD を有効化する (全ピクセルが階調 0 = 一番明るい緑になり真っ白に見える)。
; 実機ブート ROM が同じことをして、その後のアニメーションでフェードインさせる。ここでは
; 12 走査線ごとに上げるので、画面には「上ほど薄く下ほど濃い」帯が積み上がる。
;
; 走査線の検出は LY (0xFF44) で行う。LY はドット 0 で更新され、実際の画素転送はドット 80
; 以降なので、LY の変化を見て数命令で書いた SCX はその走査線の画素が描かれる前に間に合う
; (行内でちぎれない)。CA のメモリモデルは STAT を持たない (ポーリングすると永久に待つ)。
;
; LY の値は CA (wgpu-runner/src/memory.rs の set_lcd_y) と F# (src/Testbench.fs の setLcdY) が
; 同じ式で作る。どちらも program JSON の cycle (M サイクル、1 バスアクセス = 1 cycle) を 114 で
; 割る。以前は T サイクルの値 456 で割っていたため LY が実機の 4 倍遅く進み、CA と gbfs で
; SCX の進み方がずれていた (修正済み)。
; 固定ディレイで近似するのは避ける。ディレイの周期と走査線 114 M の差が位相ずれとして積もり、
; 「SCX が進まない走査線」が出る (実測: 周期 115.75 M のとき 1 フレームに 2 行、行 55 と行 120)。
;
; 歩幅は 1 にする。3 ドットずつ進めると 8 ドット周期の縞が 2.7 行ごとに回り込んで
; 密なテクスチャに見え、斜めとして読めない (実測で踏んだ)。
;
; カートリッジ ROM としてビルドし、コードを 0x0100 の入口から置く。CA のリセット PC は
; 0x0100、gbfs もブート後状態 (PC=0x0100) から始まるので、両者が同じ経路をたどる。
; ブート ROM は使わない (0x0000-0x00FF を上書きしない)。
;
;   nix shell nixpkgs#rgbds -c bash -c \
;     'rgbasm -o /tmp/scroll.o demo/scroll.asm \
;      && rgblink -o demo/scroll.gb /tmp/scroll.o && rgbfix -p 0xFF -v demo/scroll.gb'
;   cp demo/scroll.gb routed/rom_demo_scroll.bin
;   dotnet fsi src/ExportGolden.fsx routed/demo_scroll.json   # 6,000 周期ぶんの golden

SECTION "Entry", ROM0[$0100]
    nop
    jp Start

SECTION "Start", ROM0[$0150]
Start:
    ; --- LCD を切ってから VRAM を触る ---
    xor a
    ld [$FF40], a               ; LCDC = 0 (LCD off)

    ; --- タイルデータ 2 個 (1 個 = 8 行 x 2 バイト = 16 バイト、計 32 バイト) を $8000 に置く ---
    ld hl, $8000
    ld de, TileData
    ld b, 32
.copy_tiles:
    ld a, [de]
    ld [hl+], a
    inc de
    dec b
    jr nz, .copy_tiles

    ; --- タイルマップは触らない ---
    ; メモリモデルの VRAM は 0 初期化なので、タイルマップ $9800 は既にタイル 0 で埋まっている。
    ; 1024 バイトを実際に埋めると約 7,000 周期かかり、その間 LCD を切ったままにできない
    ; (LCD を点けるのは最後) ため、デモの 6,000 周期がまるごと無表示になる。

    ; --- パレットとスクロール ---
    ; BGP は $00 から始める。全ピクセルが階調 0 (一番明るい緑) になり、画面は真っ白に見える。
    ; 走査線を進めながら段階的に上げると、描かれた模様が濃くなっていく
    ; (実機ブート ROM が BGP=$00 で LCD を有効化してからフェードインさせるのと同じ見え方)。
    xor a
    ld [$FF47], a               ; BGP = $00
    ld [$FF42], a               ; SCY
    ld [$FF43], a               ; SCX
    ld b, a                     ; b = 直前に見た LY (いまは 0)
    ld hl, BgpTable             ; フェード表のポインタ (以降 hl を他に使わない)
    ld c, 12                    ; 12 走査線ごとに BGP を 1 段上げる

    ; --- LCD on + BG on ---
    ld a, %10010001
    ld [$FF40], a               ; LCDC = 0x91

.loop:
    ; LY が変わったら (= 次の走査線に入ったら) 1 回だけ処理する。
    ld a, [$FF44]               ; LY
    cp b
    jr z, .loop                 ; 同じ走査線の間は回り続ける
    ld b, a                     ; 新しい LY を覚える

    ld a, [$FF43]
    add a, 1                    ; SCX を 1 ドット右へ
    ld [$FF43], a               ; 走査線ごとに累積して縞が 45 度に傾く

    dec c
    jr nz, .loop
    ld c, 12                    ; 12 走査線ごとに BGP を 1 段
    ld a, [hl+]
    ld [$FF47], a               ; 描かれた模様が濃くなっていく
    jr .loop

BgpTable:
    ; 1 エントリ = 12 走査線ぶん。1 フレームは 131 行ほど描かれるので、10 回前後引かれる。
    ; 段を 4 エントリ (= 48 走査線) ずつにすると、フェードが画面の 2/3 を覆う。
    ; $E4 = %11100100 は index n -> shade n の恒等写像。階調 3 (模様の濃い側) の濃さだけが上がる。
    ; 注意: 先頭に $00 を並べないこと ($00 は LCD を点ける前に書いてある)。並べると
    ; 12 エントリ = 144 走査線ぶん据え置きになり、1 フレームがまるごと無地になる (実測で踏んだ)。
    db $40, $40, $40, $40       ; shade 1
    db $90, $90, $90, $90       ; shade 2
    db $E4, $E4, $E4, $E4       ; shade 3 (恒等写像)。以降は据え置き
    db $E4, $E4, $E4, $E4, $E4, $E4, $E4, $E4

TileData:
    ; タイル 0: 4 ドット幅の縦縞 (8 ドット周期)。8 行すべて同じパターン。
    ; 行が同じなので、SCX を走査線ごとにずらすと縞がそのまま斜めになる。
    ; 周期 2 のチェッカーだと 3 ドットのずれが「反転」に見えて斜めに見えない (実測で踏んだ)。
    ; 1 タイル = 8 行 x 2 バイト (上位プレーン, 下位プレーン) であることに注意。
    ; 16 バイトで 2 タイルぶんと書くと、後半 4 行が別タイルのデータになって
    ; 「数行おきに空白行」が出る (実測で踏んだ)。
    db %11110000, %11110000     ; 行 0
    db %11110000, %11110000     ; 行 1
    db %11110000, %11110000     ; 行 2
    db %11110000, %11110000     ; 行 3
    db %11110000, %11110000     ; 行 4
    db %11110000, %11110000     ; 行 5
    db %11110000, %11110000     ; 行 6
    db %11110000, %11110000     ; 行 7
    ; タイル 1: 16 ドット幅の縞 (予備、タイルマップからは使っていない)
    db %11111111, %11111111
    db %11111111, %11111111
    db %00000000, %00000000
    db %00000000, %00000000
    db %11111111, %11111111
    db %11111111, %11111111
    db %00000000, %00000000
    db %00000000, %00000000