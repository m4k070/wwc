; demo/scroll.asm — CA デモ映像用の最小 ROM (rgbds)
;
; 目的: CA (sm83_full) の実行と gbfs の PPU 出力を並べて撮るための題材。
; LCD を有効化してタイル 0 の縦縞を BG に敷き、**走査線ごとに SCX を 1 進める**。
; 縞が斜めに流れるので、左の CA の信号の動きと対応させて見せられる。
;
; 動きの設計: PPU は 1 フレームを 17,556 バス周期かけて描くので、フレーム単位の
; スクロール (SCY を VBlank で更新する等) では 6,000 周期の撮影中に 1 回も変化しない。
; 1 フレームの内側で見える動きは「描いている最中のレジスタを書き換える」形しかない。
; 約 1 走査線ぶん (112 M サイクル) 待ってから SCX を 1 進める、を繰り返すと、
; 走査線ごとに描画開始位置が 1 ドットずつずれて縞が 45 度に傾く。
;
; 歩幅は 1 にする。3 ドットずつ進めると 8 ドット周期の縞が 2.7 行ごとに回り込んで
; 密なテクスチャに見え、斜めとして読めない (実測で踏んだ。PPU の画像を視覚で見ても
; 「縦縞」と判定された)。1 ドットなら 8 ドット周期の縞がそのまま 45 度になる。
;
; LY (0xFF44) は使わない。CA 側の LY は set_lcd_y が cycle/456 で作っており
; (wgpu-runner/src/memory.rs)、program JSON の cycle は M サイクル (1 バスアクセス = 1 cycle)
; なので、**CA の LY は gbfs の PPU より 4 倍遅く進む** (実測: 6,000 cycle で LY=13。
; 実機なら 52 のはず)。LY で更新すると CA と gbfs で SCX の進み方がずれ、並べた 2 つの絵が
; 食い違う。固定ディレイなら両者が同じコードを同じ速度で実行する。
; CA のメモリモデルは STAT も持たない (ポーリングすると CA 上では永久に待つ)。
;
; カートリッジ ROM としてビルドし、コードを 0x0100 の入口から置く。CA のリセット PC は
; 0x0100、gbfs もブート後状態 (PC=0x0100) から始まるので、両者が同じ経路をたどる。
; ブート ROM は使わない (0x0000-0x00FF を上書きしない)。
;
;   nix shell nixpkgs#rgbds -c bash -c \
;     'rgbasm -o /tmp/scroll.o demo/scroll.asm \
;      && rgblink -o demo/scroll.gb /tmp/scroll.o && rgbfix -p 0xFF -v demo/scroll.gb'
;   cp demo/scroll.gb routed/rom_demo_scroll.bin
;   dotnet fsi src/ExportGolden.fsx routed/demo_scroll.json   # 6,000 周期ぶんの golden

SECTION "Entry", ROM0[$0100]
    nop
    jp Start

SECTION "Start", ROM0[$0150]
Start:
    ; --- LCD を切ってから VRAM を触る ---
    xor a
    ld [$FF40], a               ; LCDC = 0 (LCD off)

    ; --- タイルデータ 2 個 (1 個 = 8 行 x 2 バイト = 16 バイト、計 32 バイト) を $8000 に置く ---
    ld hl, $8000
    ld de, TileData
    ld b, 32
.copy_tiles:
    ld a, [de]
    ld [hl+], a
    inc de
    dec b
    jr nz, .copy_tiles

    ; --- タイルマップは触らない ---
    ; メモリモデルの VRAM は 0 初期化なので、タイルマップ $9800 は既にタイル 0 で埋まっている。
    ; 1024 バイトを実際に埋めると約 7,000 周期かかり、その間 LCD を切ったままにできない
    ; (LCD を点けるのは最後) ため、デモの 6,000 周期がまるごと無表示になる。

    ; --- パレットとスクロール ---
    ld a, %11100100
    ld [$FF47], a               ; BGP
    xor a
    ld [$FF42], a               ; SCY
    ld [$FF43], a               ; SCX

    ; --- LCD on + BG on ---
    ld a, %10010001
    ld [$FF40], a               ; LCDC = 0x91

.loop:
    ; 1 走査線ぶん待ってから SCX を進める。
    ; LY (0xFF44) は使わない — CA 側の LY は set_lcd_y が cycle/456 で作っており
    ; (wgpu-runner/src/memory.rs)、program JSON の cycle は M サイクルなので
    ; CA の LY は gbfs の PPU より 4 倍遅く進む (実測: 6,000 cycle で LY=13。実機なら 52)。
    ; 同じ ROM を CA と gbfs の両方で走らせるデモでは、両者の SCX の進み方がずれてしまう。
    ; 固定ディレイなら両者が同じコードを同じ速度で実行する。
    ; ld b,n + n x (dec b + jr nz) = 2 + 4n M サイクル。
    ld b, 25                    ; 2 + 100 = 102 M サイクル
.wait:
    dec b
    jr nz, .wait
    ld a, [$FF43]               ; SCX (上のディレイと合わせて約 112 M サイクルごと)
    add a, 1
    ld [$FF43], a               ; 1 ドットずつ右へ。走査線ごとに累積して 45 度に傾く
    jr .loop

TileData:
    ; タイル 0: 4 ドット幅の縦縞 (8 ドット周期)。8 行すべて同じパターン。
    ; 行が同じなので、SCX を走査線ごとにずらすと縞がそのまま斜めになる。
    ; 周期 2 のチェッカーだと 3 ドットのずれが「反転」に見えて斜めに見えない (実測で踏んだ)。
    ; 1 タイル = 8 行 x 2 バイト (上位プレーン, 下位プレーン) であることに注意。
    ; 16 バイトで 2 タイルぶんと書くと、後半 4 行が別タイルのデータになって
    ; 「数行おきに空白行」が出る (実測で踏んだ)。
    db %11110000, %11110000     ; 行 0
    db %11110000, %11110000     ; 行 1
    db %11110000, %11110000     ; 行 2
    db %11110000, %11110000     ; 行 3
    db %11110000, %11110000     ; 行 4
    db %11110000, %11110000     ; 行 5
    db %11110000, %11110000     ; 行 6
    db %11110000, %11110000     ; 行 7
    ; タイル 1: 16 ドット幅の縞 (予備、タイルマップからは使っていない)
    db %11111111, %11111111
    db %11111111, %11111111
    db %00000000, %00000000
    db %00000000, %00000000
    db %11111111, %11111111
    db %11111111, %11111111
    db %00000000, %00000000
    db %00000000, %00000000
